"""
Compare tokens generated by tiny-vllm with greedy decoding in HuggingFace transformers.
Usage:
    ./build/tiny-vllm | python python/compare_with_hf.py
Prompts and BATCH_SIZE are read from src/main.cpp, so run it from the repository root.
"""

import argparse
import re
import sys

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer

STOP_TOKENS = {128001, 128009}  # <|end_of_text|>, <|eot_id|>


def read_main_cpp(path):
    src = open(path).read()
    prompts = [
        [int(tok) for tok in ids.split(",")]
        for ids in re.findall(r"queue\.push\(\{([\d,\s]+)\}\)", src)
    ]
    batch_size = int(re.search(r"BATCH_SIZE = (\d+)", src).group(1))
    return prompts, batch_size


# tiny-vllm prints tokens of all slots interleaved, in the order they are generated.
# This follows the same slot logic as the loop in main.cpp to split them per prompt
def split_per_prompt(tokens, num_prompts, batch_size):
    tokens = iter(tokens)
    generated = [[] for _ in range(num_prompts)]
    slots = [None] * batch_size  # which prompt is in which slot
    next_prompt = 0
    while True:
        for slot in range(batch_size):
            if slots[slot] is None and next_prompt < num_prompts:
                # prefill prints the first token
                slots[slot] = next_prompt
                generated[next_prompt].append(next(tokens))
                next_prompt += 1
        if all(prompt is None for prompt in slots):
            return generated
        for slot in range(batch_size):
            prompt = slots[slot]
            if prompt is None:
                continue
            token = next(tokens)
            generated[prompt].append(token)
            if token in STOP_TOKENS:
                slots[slot] = None


def greedy(model, prompt, max_new_tokens):
    generated = []
    ids = torch.tensor([prompt])
    past = None
    with torch.no_grad():
        for _ in range(max_new_tokens):
            out = model(ids, past_key_values=past, use_cache=True)
            past = out.past_key_values
            token = int(torch.argmax(out.logits[0, -1]))
            generated.append(token)
            if token in STOP_TOKENS:
                break
            ids = torch.tensor([[token]])
    return generated


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", default="meta-llama/Llama-3.2-1B-Instruct")
    parser.add_argument("--main-cpp", default="src/main.cpp")
    parser.add_argument("--max-new-tokens", type=int, default=64)
    args = parser.parse_args()

    prompts, batch_size = read_main_cpp(args.main_cpp)
    printed = [int(tok) for tok in re.findall(r"token index: (\d+)", sys.stdin.read())]
    ours = split_per_prompt(printed, len(prompts), batch_size)

    tokenizer = AutoTokenizer.from_pretrained(args.model)
    model = AutoModelForCausalLM.from_pretrained(args.model, torch_dtype=torch.bfloat16)
    model.eval()

    mismatches = 0
    for i, prompt in enumerate(prompts):
        expected = greedy(model, prompt, args.max_new_tokens)
        ok = ours[i][: args.max_new_tokens] == expected
        mismatches += not ok
        print(f"\nPrompt {i}: {'OK' if ok else 'MISMATCH'}")
        print(f"  transformers: {expected} {tokenizer.decode(expected)!r}")
        print(f"  tiny-vllm:    {ours[i]} {tokenizer.decode(ours[i])!r}")

    sys.exit(1 if mismatches else 0)


if __name__ == "__main__":
    main()
